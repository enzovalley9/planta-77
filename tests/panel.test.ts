  expect(still.find((n) => n.key === 'wheel-top')).toBeUndefined()
  await h.raise('ui.fault', { ...fault, requestId: 'planta-77', element: 'ui' })
  expect(h.d.invalidated).toBe(marks + 1)
  await h.run('office', 'diag')
  const seq = (await h.draw()).find((n) => n.key === 'ui').props.props.diag
  await h.post({ kind: 'diag', seq, fps: 60, renders: 1, maxGap: 16, layers: '0/0', pages: 0, lod: 1, msgs: 12, cols: COLS, rows: ROWS })
