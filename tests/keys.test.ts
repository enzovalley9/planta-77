import { expect, test } from 'claude-code/testing'
import { world, openStage, uiProps, uiTexts, twin, arrive, offCamera, opened, urlOf, sid, COLS, ROWS } from './fixture'

const FLIGHT = { timeoutMs: 20000 }
const press = async (pane: any, ...keys: string[]) => { for (const key of keys) await pane.key({ key, in: 'ui' }) }

test('the keys zoom at the centre, move around and go back to the whole floor', FLIGHT, async ($, on) => {
  const w = world(on)
  const pane = await openStage($)
  const t = twin(await uiProps(pane))
  const home = t.home(), mid = [COLS / 2, ROWS / 2] as const
  await press(pane, '+', '=')
  await arrive(pane, 240)
  const near = t.zoom(home, ...mid, 1.6 * 1.6)
  expect(await offCamera(pane, near)).toEqual([])
  expect(await offCamera(pane, home)).not.toEqual([])
  await press(pane, 'left', 'up')
  await arrive(pane, 200)
  const moved = t.pan(t.pan(near, -0.22, 0), 0, -0.22)
  expect(moved.cx).toBeLessThan(near.cx)
  expect(moved.cy).toBeLessThan(near.cy)
  expect(await offCamera(pane, moved)).toEqual([])
  expect(await offCamera(pane, near)).not.toEqual([])
  await press(pane, 'd', 's')
  await arrive(pane, 200)
  expect(await offCamera(pane, near)).toEqual([])
  await press(pane, 'a', 'w', 'right', 'down', '-')
  await arrive(pane, 240)
  const out = t.zoom(near, ...mid, 1 / 1.6)
  expect(await offCamera(pane, out)).toEqual([])
  expect(await offCamera(pane, near)).not.toEqual([])
  await press(pane, '0')
  await arrive(pane, 460)
  expect(await offCamera(pane, home)).toEqual([])
  expect(opened(w)).toEqual([])
})

test('N and P walk the sessions waiting for you, Enter opens the highlighted one and a number jumps to that room', FLIGHT, async ($, on) => {
  const w = world(on)
  const pane = await openStage($)
  const ui = await uiProps(pane), t = twin(ui)
  await press(pane, 'return')
  expect(opened(w)).toEqual([])
  await press(pane, 'n', 'return', 'n', 'return', 'p', 'return', 'p', 'return', 'space', 'return')
  expect(opened(w)).toEqual([urlOf(2), urlOf(3), urlOf(2), urlOf(5), urlOf(2)])
  await press(pane, 'n')
  await arrive(pane, 520)
  expect(await offCamera(pane, t.toSession(sid(3)))).toEqual([])
  await press(pane, '6')
  await arrive(pane, 520)
  expect(ui.rooms[5].n).toBe('RAMEN')
  expect(await offCamera(pane, t.room(ui.rooms[5].id))).toEqual([])
  expect(await offCamera(pane, t.toSession(sid(3)))).not.toEqual([])
  await press(pane, 'f')
  await arrive(pane, 460)
  expect(await offCamera(pane, t.home())).toEqual([])
  expect(opened(w)).toHaveLength(5)
})

test('? and H show and hide the controls, and C goes to the cameras and back', async ($, on) => {
  const w = world(on)
  const pane = await openStage($)
  expect(await uiTexts(pane)).toContain('drag to move · wheel or + − to zoom · click a room to enter · click someone to open their session · ? for help')
  await press(pane, '?')
  const help = await uiTexts(pane)
  expect(help).toContain('CONTROLS')
  expect(help).toContain('N · P')
  expect(help.some((text) => text.startsWith('drag to move ·'))).toBe(false)
  await press(pane, 'h')
  expect(await uiTexts(pane)).not.toContain('CONTROLS')
  await press(pane, 'c')
  expect((await uiProps(pane)).mode).toBe('cameras')
  await press(pane, '?')
  expect(await uiTexts(pane)).toContain('CONTROLS')
  await press(pane, '?', 'c')
  expect((await uiProps(pane)).mode).toBe('office')
  await press(pane, 'c', '0')
  expect((await uiProps(pane)).mode).toBe('office')
  expect(opened(w)).toEqual([])
})
