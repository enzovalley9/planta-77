test('a view message with a detail level switches the list between the packed floor and the per-room layers, and odd levels change nothing', async ($, on) => {
  const w = world(on)
  const pane = await openStage($)
  const snap = snapOf(w), scene = buildScene(snap, { hour: 22, aspect: ASPECT })
  const tier = (lod: number) => { const base = tierLayers(scene, snap, lod) as any[]; return [...base.filter((l) => !l.fx), ...base.filter((l) => l.fx)] }
  const start = await uiProps(pane), lab = pairs(labels(start.man))
  expect(start.lod).toBe(1)
  for (const lod of [2, 0, 1, 2]) {
    await pane.post({ kind: 'view', bucket: 0, lod }, { in: 'ui' })
    const ui = await uiProps(pane), base = scenery(ui.man)
    expect(ui.lod).toBe(lod)
    expect(pairs(base)).toEqual(pairs(tier(lod)))
    expect(pairs(labels(ui.man))).toEqual(lab)
    expect(base.every((m) => (m.fx === 1) === /^(x\d|fx)/.test(m.id))).toBe(true)
    if (lod < 2) {
      expect(base.every((m) => new RegExp(`^[wx]${lod}-\\d+$`).test(m.id) && !m.box && !m.room)).toBe(true)
      expect(base.length).toBeLessThan(tier(2).length)
    } else {
      for (const r of ui.rooms) {
        expect(base.find((m) => m.id === r.id), r.n).toMatchObject({ room: r.id, box: expect.any(Array) })
        expect(base.find((m) => m.id === `fx-${r.id}`), r.n).toMatchObject({ room: r.id, fx: 1, box: expect.any(Array) })
      }
      expect(base.filter((m) => m.room).length).toBe(ui.rooms.length * 2)
      expect(base.filter((m) => !m.room).map((m) => m.id)).toEqual(expect.arrayContaining(['sky', 'slab']))
    }
  }
  for (const lod of [3, -1, 1.5, '1', null, true]) await pane.post({ kind: 'view', bucket: 0, lod } as any, { in: 'ui' })
  expect((await uiProps(pane)).lod).toBe(2)
  await pane.post({ kind: 'view', bucket: 4 }, { in: 'ui' })
  expect(await uiProps(pane)).toMatchObject({ bucket: 4, lod: 2 })
  for (const bucket of [-1, LABEL_BUCKETS, 2.5, '2', null]) await pane.post({ kind: 'view', bucket, lod: 0 } as any, { in: 'ui' })
  await pane.post({ kind: 'view', lod: 0 } as any, { in: 'ui' })
  expect(await uiProps(pane)).toMatchObject({ bucket: 4, lod: 2 })
})

